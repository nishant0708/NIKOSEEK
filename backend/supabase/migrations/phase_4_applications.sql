create table if not exists job_applications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  job_id bigint not null references scraped_jobs(id) on delete cascade,
  resume_key text not null,
  resume_role varchar(100),
  status varchar(40) not null default 'PENDING',
  stage varchar(100) not null default 'QUEUED',
  queue_position integer not null default 0,
  application_url text,
  form_data jsonb not null default '{}'::jsonb,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  started_at timestamptz,
  applied_at timestamptz,
  completed_at timestamptz
);

create unique index if not exists job_applications_user_job_idx on job_applications(user_id, job_id);
create index if not exists job_applications_user_status_idx on job_applications(user_id, status, queue_position);

alter table scraped_jobs add column if not exists application_status varchar(40) not null default 'PENDING';
alter table scraped_jobs add column if not exists application_id bigint references job_applications(id) on delete set null;
alter table scraped_jobs add column if not exists resume_key text;
alter table scraped_jobs add column if not exists resume_role varchar(100);
alter table scraped_jobs add column if not exists applied_at timestamptz;
