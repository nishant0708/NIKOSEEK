-- Phase 6: step-by-step agent log for every application run (Postgres / Supabase).
-- Safe to run more than once.
create table if not exists job_application_events (
  id bigint generated by default as identity primary key,
  application_id bigint not null references job_applications(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  attempt integer not null default 1,
  stage_key varchar(20) not null default 'open',   -- open | login | find | fields | review | failed
  kind varchar(20) not null default 'info',        -- stage | thinking | action | info | warning | error
  message text not null,
  data jsonb not null default '{}'::jsonb,         -- AI decision, url, clicked element, field counts, ...
  created_at timestamptz not null default now()
);

create index if not exists job_application_events_app_attempt_idx
  on job_application_events (application_id, attempt, id);
create index if not exists ix_job_application_events_user_id
  on job_application_events (user_id);
