-- Phase 8: resume agent (Postgres / Supabase). Safe to run more than once.
alter table scraped_jobs add column if not exists resume_category varchar(100);
alter table job_applications add column if not exists resume_agent jsonb not null default '{}'::jsonb;

create table if not exists resumes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  storage_key text not null,
  category varchar(100) not null,
  label varchar(200) not null,
  origin varchar(20) not null default 'uploaded',      -- uploaded | generated
  parent_id bigint references resumes(id) on delete set null,
  source_job_id bigint references scraped_jobs(id) on delete set null,
  upload_name varchar(200) not null,                   -- file name shown on LinkedIn / Indeed
  content jsonb not null default '{}'::jsonb,          -- structured resume (generated ones)
  text text,                                           -- cached plain text used for scoring
  created_at timestamptz not null default now(),
  constraint uq_user_resume_key unique (user_id, storage_key)
);
create index if not exists ix_resumes_user_id on resumes (user_id);
create index if not exists ix_resumes_category on resumes (category);

create table if not exists resume_portal_uploads (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  resume_id bigint not null references resumes(id) on delete cascade,
  portal varchar(50) not null,                         -- linkedin | indeed
  display_name varchar(255) not null,
  uploaded_at timestamptz not null default now(),
  last_used_at timestamptz,
  constraint uq_resume_portal unique (resume_id, portal)
);
create index if not exists ix_resume_portal_uploads_user_id on resume_portal_uploads (user_id);
