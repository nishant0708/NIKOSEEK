-- Run after the existing MVP tables have been created by the backend.
create table if not exists search_runs (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  parameters jsonb not null default '{}'::jsonb,
  status varchar(20) not null default 'RUNNING',
  fetched_count integer not null default 0,
  accepted_count integer not null default 0,
  rejected_count integer not null default 0,
  error text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

alter table scraped_jobs add column if not exists search_run_id bigint references search_runs(id) on delete set null;
alter table scraped_jobs add column if not exists ai_status varchar(20) not null default 'PENDING';
alter table scraped_jobs add column if not exists match_score double precision;
alter table scraped_jobs add column if not exists ai_reason text;
alter table scraped_jobs add column if not exists experience_match varchar(100);
create index if not exists scraped_jobs_user_status_idx on scraped_jobs(user_id, ai_status, match_score desc);
