alter table users add column if not exists is_admin boolean not null default false;
alter table users add column if not exists agent_config jsonb not null default '{}'::jsonb;

alter table search_runs add column if not exists llm_input_tokens integer not null default 0;
alter table search_runs add column if not exists llm_output_tokens integer not null default 0;
alter table search_runs add column if not exists llm_total_tokens integer not null default 0;

alter table scraped_jobs add column if not exists llm_input_tokens integer not null default 0;
alter table scraped_jobs add column if not exists llm_output_tokens integer not null default 0;
alter table scraped_jobs add column if not exists llm_total_tokens integer not null default 0;

create table if not exists system_prompts (
  id bigint generated by default as identity primary key,
  key varchar(100) not null unique,
  content text not null,
  updated_by_user_id bigint references users(id) on delete set null,
  updated_at timestamptz not null default now()
);
